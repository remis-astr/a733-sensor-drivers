"""Regenerates imx477_tables.h from the "planetary" IMX477 driver used on the
Raspberry Pi (raspberrypi/linux rpi-6.12.y imx477.c + 8 crop modes, from the
Multicam project's usr/src/imx477-planetary/imx477.c).

    python3 extract_tables.py /path/to/imx477.c

Copied unchanged (order and values): mode_common_regs and the register table
of every mode in supported_modes[]; width, height and frm_length_default of
each mode. The two symbolic entries of mode_common_regs (IOP_SYSCK_DIV,
IOP_PREDIV) are 0x02.
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1]).read_text()
out_path = Path(__file__).with_name("imx477_tables.h")
reg = re.compile(r"\{\s*CCI_REG8\((0x[0-9a-fA-F]+)\)\s*,\s*(0x[0-9a-fA-F]+)\s*\}")
sym = {"IMX477_REG_IOP_SYSCK_DIV": "0x030b", "IMX477_REG_IOP_PREDIV": "0x030d"}


def table(name: str) -> list[tuple[str, str]]:
    i = src.index(f"cci_reg_sequence {name}[] = {{")
    body = src[i:src.index("};", i)]
    regs = []
    for line in body.splitlines()[1:]:
        m = reg.search(line)
        if m:
            regs.append((m.group(1).lower(), m.group(2).lower()))
            continue
        for k, a in sym.items():
            if f"{{{k}," in line.replace(" ", ""):
                regs.append((a, "0x02"))
    return regs


i = src.index("static const struct imx477_mode supported_modes[] = {")
modes_src = src[i:src.index("\n};", i)]
modes = []
for blk in re.split(r"\n\t\{\n", modes_src)[1:]:
    w = int(re.search(r"\.width = (\d+)", blk).group(1))
    h = int(re.search(r"\.height = (\d+)", blk).group(1))
    frm = int(re.search(r"\.frm_length_default = (\d+)", blk).group(1))
    regs = re.search(r"\.regs = (\w+)", blk).group(1)
    comment = re.search(r"/\*\s*(.*?)\s*\*/", blk).group(1)
    modes.append((w, h, frm, regs, comment))

out = ["/* SPDX-License-Identifier: GPL-2.0 */",
       "/*",
       " * IMX477 register tables, extracted unchanged (order and values) from the",
       " * Raspberry Pi imx477.c with Multicam's planetary crop modes",
       " * (minicam_program usr/src/imx477-planetary, raspberrypi/linux rpi-6.12.y).",
       " * Generated by drivers/imx477/extract_tables.py — do not edit by hand.",
       " */", ""]
for name in ["mode_common_regs"] + sorted({m[3] for m in modes}):
    regs = table(name)
    out.append(f"static struct regval_list imx477_{name}[] = {{")
    for k in range(0, len(regs), 4):
        out.append("\t" + " ".join(f"{{{a}, {v}}}," for a, v in regs[k:k + 4]))
    out += ["};", ""]
    print(f"{name}: {len(regs)} registres")
out.append("/* width, height, frm_length_default, registers — supported_modes[] order */")
out.append("#define IMX477_PI_MODES \\")
for w, h, frm, regs, comment in modes:
    out.append(f"\tIMX477_MODE({w}, {h}, {frm}, imx477_{regs}) /* {comment} */ \\")
out[-1] = out[-1].rstrip(" \\")   # pas de « \ » final
out.append("")
out_path.write_text("\n".join(out))
print(f"{len(modes)} modes")
