"""Regenerates starvis2_tables.h from Will Whang's Raspberry Pi drivers.
    git clone https://github.com/will127534/imx585-v4l2-driver   (same for 678, 662)
    python3 extract_tables.py <folder holding the three repositories>
Tables copied unchanged (order and values): imx585.c common_regs +
common_normal_mode, imx678.c and imx662.c common_regs (commented-out lines
skipped).
"""
import re
import sys
from pathlib import Path

base = Path(sys.argv[1] if len(sys.argv) > 1 else ".")
out_path = Path(__file__).with_name("starvis2_tables.h")


def block(src: str, name: str) -> str:
    i = src.index(name)
    return src[i:src.index("};", i)]


pat585 = re.compile(r"CCI_REG8\((0x[0-9a-fA-F]+)\),\s*(0x[0-9a-fA-F]+)")
patold = re.compile(r"\{\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+)\s*\}")
out = ["/* SPDX-License-Identifier: GPL-2.0 */",
       "/*",
       " * Sensor init tables of the Sony Starvis 2 sensors, extracted unchanged",
       " * (order and values) from Will Whang's Raspberry Pi drivers",
       " * (github.com/will127534/imx{585,678,662}-v4l2-driver, GPL-2.0):",
       " *   imx585.c: common_regs + common_normal_mode (normal, non-HDR mode);",
       " *   imx678.c, imx662.c: common_regs.",
       " * Generated by drivers/starvis2/extract_tables.py — do not edit by hand.",
       " */", ""]
for chip in ("585", "678", "662"):
    src = (base / f"imx{chip}-v4l2-driver" / f"imx{chip}.c").read_text()
    if chip == "585":
        regs = (pat585.findall(block(src, "common_regs[] = {"))
                + pat585.findall(block(src, "common_normal_mode[] = {")))
    else:
        b = block(src, "common_regs[] = {")
        b = "\n".join(l for l in b.splitlines() if not l.strip().startswith("//"))
        regs = patold.findall(b)
    out += [f"#ifdef STARVIS2_IMX{chip}", "static struct regval_list starvis2_common_regs[] = {"]
    for k in range(0, len(regs), 4):
        out.append("\t" + " ".join(f"{{{a.lower()}, {v.lower()}}}," for a, v in regs[k:k + 4]))
    out += ["};", f"#endif /* STARVIS2_IMX{chip} */", ""]
    print(f"IMX{chip}: {len(regs)} registres")
out_path.write_text("\n".join(out))
